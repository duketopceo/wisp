#!/usr/bin/env python3
"""Generate shell-plugin/lib/status.js from wisp/status.py (plan KTD1).

    python scripts/assets/gen_status.py          # write status.js
    python scripts/assets/gen_status.py --check  # exit 1 if status.js is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from wisp import status as wstatus  # noqa: E402

OUT = ROOT / "shell-plugin" / "lib" / "status.js"

_FUNCTIONS = r"""
// The row for a daemon status or a derived state; unknown reads offline.
function row(status) {
  return ROWS.hasOwnProperty(status) ? ROWS[status] : ROWS[UNKNOWN_STATUS]
}

function isStatus(status) { return STATUSES.indexOf(status) >= 0 }

// The row for a daemon status only; unknown (or a derived key) reads offline.
function statusRow(status) { return ROWS[isStatus(status) ? status : UNKNOWN_STATUS] }

function statusWord(status) { return Copy.string(statusRow(status).word) }

function statusTone(status) { return statusRow(status).tone }

// The short word's copy key (the bar pill); equals the main word or is a
// prefix of it.
function shortKey(status) { return statusRow(status).short }

function shortWord(status) { return Copy.string(statusRow(status).short) }

// Mark glyph and token by daemon status.
function markIcon(status) { return statusRow(status).glyph }

function markToken(status) { return statusRow(status).mark_token }

// Creature state for a daemon status; unknown reads offline.
function creatureState(status) { return statusRow(status).creature }

// Creature halo token by creature state (a transient has no row: ember).
function creatureToken(state) {
  var keys = STATUSES.concat(DERIVED)
  for (var i = 0; i < keys.length; i++)
    if (ROWS[keys[i]].creature === state) return ROWS[keys[i]].creature_token
  return "ember"
}

// Buddy mode by status: hidden, waveform, spinner, triangle or
// triangleNeedsYou.
function buddyMode(status) { return statusRow(status).buddy }

function buddyLive() {
  var out = []
  for (var i = 0; i < STATUSES.length; i++)
    if (ROWS[STATUSES[i]].buddy !== "hidden") out.push(STATUSES[i])
  return out
}

// Which row the bar reads for a status plus context. o: {status, result,
// confirm, offline}. Error wins, then a pending choice, a confirmation or
// a blocked turn, else the status itself. "" for a status the table does
// not know.
function rowKey(o) {
  var s = String(o.status)
  if (o.offline || s === "offline") return "offline"
  if (s === "error") return "error"
  if (s === "awaiting_choice") return "awaiting_choice"
  if (o.confirm === true) return "confirm"
  if (s === "done" && /^BLOCKED/.test(String(o.result || ""))) return "blocked"
  return isStatus(s) ? s : ""
}

// The error cause word's text for an error code; "" when there is none.
function causeWord(code) {
  var c = ROWS.error.causes
  return c.hasOwnProperty(code) ? Copy.string(c[code]) : ""
}

// Live-state word for every surface (pill, status line, bar tooltip).
// Mirrors copy.word_view: stale busy reads reconnecting, an error with a
// code reads its message, a done turn with a BLOCKED result reads blocked,
// anything else is the status word.
function wordView(status, result, code, stale) {
  var key = ""
  if (stale && BUSY.indexOf(status) >= 0) key = "stale"
  else if (status === "error" && code)
    return { word: Copy.errorMessage(code), tone: "fail" }
  else if (status === "done" && /^BLOCKED/.test(result || "")) key = "blocked"
  else key = isStatus(status) ? status : UNKNOWN_STATUS
  return { word: Copy.string(row(key).word), tone: row(key).tone }
}

function pillView(status, result) { return wordView(status, result, "", false) }
"""


def render() -> str:
    def js(v):
        return json.dumps(v, ensure_ascii=True)
    return "\n".join([
        ".pragma library",
        ".import \"copy.js\" as Copy",
        "",
        "// GENERATED by scripts/assets/gen_status.py from wisp/status.py.",
        "// Do not edit; change wisp/status.py and regenerate. Words are copy",
        "// keys (lib/copy.js STRINGS); this file holds no text and no colours.",
        "",
        f"var STATUSES = {js(list(wstatus.STATUSES))}",
        f"var DERIVED = {js(list(wstatus.DERIVED))}",
        f"var UNKNOWN_STATUS = {js(wstatus.UNKNOWN_STATUS)}",
        f"var BUSY = {js(list(wstatus.BUSY))}",
        f"var ROWS = {js(wstatus.ROWS)}",
    ]) + "\n" + _FUNCTIONS


def main(argv) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run "
                  "python scripts/assets/gen_status.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
